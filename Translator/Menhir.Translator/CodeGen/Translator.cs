using System.Globalization;
using System.Reflection.Metadata;
using System.Text;
using Menhir.Translator.TypeSystem;

namespace Menhir.Translator.CodeGen;

/// <summary>
/// Translates loaded assemblies into one C file for Engine/Runtime: type layouts, type infos and
/// vtables, statics, string literals, and every method body (see <see cref="MethodCompiler"/>).
/// </summary>
public sealed class Il2cTranslator
{
    private readonly Dictionary<TypeDesc, List<MethodDesc?>> _vtables = new();
    private readonly Dictionary<string, string> _strings = new();
    private readonly StringBuilder _stringDefinitions = new();
    private readonly Dictionary<FieldDesc, (string Name, int Size)> _rvaData = new();
    private readonly StringBuilder _rvaDefinitions = new();
    private readonly HashSet<TypeDesc> _arrayTypes = new();
    private readonly List<TypeDesc> _types;
    private readonly HashSet<TypeDesc> _typeSet;
    private readonly Queue<MethodDesc> _pending = new();
    private readonly HashSet<MethodDesc> _requested = new();
    private readonly List<MethodDesc> _methods = new();
    private readonly Dictionary<TypeDesc, List<(TypeDesc Interface, List<MethodDesc?> Methods)>> _interfaceMaps = new();
    private readonly HashSet<MethodDesc> _unboxingStubs = new();

    public Il2cTranslator(TypeSystemContext context)
    {
        Context = context;
        _types = context.AllDefinitions
            .Where(t => !t.IsGenericDefinition && !(t.DeclaringType?.IsGenericDefinition ?? false))
            .OrderBy(t => t.Module == context.CoreLib ? 0 : 1)
            .ThenBy(t => t.FullName, StringComparer.Ordinal)
            .ToList();
        _typeSet = _types.ToHashSet();
    }

    public TypeSystemContext Context { get; }
    public CNames Names { get; } = new();

    /// <summary>
    /// Full name of the base class of a game's scripts ("MenhirEngine.Script"): when set, the C gets
    /// the m_scripts table the player runs them with (see <see cref="ScriptGlue"/>).
    /// </summary>
    public string? ScriptBaseType { get; init; }

    /// <summary>Problems found while translating, as "method: reason".</summary>
    public List<string> Errors { get; } = new();

    /// <summary>
    /// The whole program as C. <paramref name="entryPoint"/> ("Namespace.Type.Method", a static
    /// method taking nothing or string[] and returning void or int) gets a C main().
    /// </summary>
    public string Translate(string? entryPoint)
    {
        foreach (TypeDesc type in _types.ToList())
        {
            BuildVTable(type);
            foreach (MethodDesc method in type.Methods.Where(m => !m.IsGeneric))
                RequireMethod(method);
        }
        foreach (TypeDesc type in _types.ToList())
            BuildInterfaceMap(type);

        MethodDesc? entry = entryPoint != null ? FindEntryPoint(entryPoint) : null;
        if (entry != null)
            UseArrayType(Context.MakeArray(Context.StringType));

        // Method bodies first: they register the string literals, arrays, data, generic
        // instantiations and methods they use, which are compiled in turn.
        var bodies = new StringBuilder();
        while (_pending.TryDequeue(out MethodDesc? method))
        {
            RequireType(method.Owner);
            if (IsDelegate(method.Owner) && !method.HasBody && method.Name is ".ctor" or "Invoke")
            {
                _methods.Add(method);
                bodies.Append(DelegateMethod(method)).Append('\n');
                continue;
            }
            if (method.IsInternalCall || method.HasBody)
                _methods.Add(method);
            if (!method.HasBody || method.IsInternalCall)
                continue;
            try
            {
                bodies.Append(new MethodCompiler(this, method).Compile()).Append('\n');
            }
            catch (TranslationException e)
            {
                Errors.Add($"{method}: {e.Message}");
            }
        }
        if (Errors.Count > 0)
            throw new TranslationException("Translation failed:\n  " + string.Join("\n  ", Errors));

        var c = new StringBuilder();
        c.Append("/* Generated by Menhir IL2C. Do not edit. */\n");
        c.Append("#include \"menhir/runtime.h\"\n#include <stdio.h>\n\n");
        WriteTypeDeclarations(c);
        WriteStructs(c);
        WriteTypeInfoDeclarations(c);
        WriteStatics(c);
        WritePrototypes(c);
        c.Append("/* ---- String literals and constant data ---- */\n\n");
        c.Append(_stringDefinitions).Append(_rvaDefinitions).Append('\n');
        WriteUnboxingStubs(c);
        WriteVTablesAndTypeInfos(c);
        WriteClassInits(c);
        c.Append("/* ---- Methods ---- */\n\n").Append(bodies);
        WriteExceptionFactory(c);
        if (ScriptBaseType != null)
            new ScriptGlue(this).Write(c, _types, ScriptBaseType);
        if (entry != null)
            WriteMain(c, entry);
        return c.ToString();
    }

    // ---- Generic instantiations, compiled on demand --------------------------------------------

    /// <summary>
    /// Makes an instantiated generic type part of the program: its layout, type info, vtable and
    /// all its methods (definitions are always part of it).
    /// </summary>
    public void RequireType(TypeDesc? type)
    {
        if (type == null)
            return;
        if (type.IsArray || type.IsByRef || type.IsPointer)
        {
            RequireType(type.ElementType);
            return;
        }
        if (!type.IsInstantiation || type.ContainsGenericParameters || !_typeSet.Add(type))
            return;
        _types.Add(type);
        RequireType(type.BaseType);
        foreach (FieldDesc field in type.Fields)
            RequireType(field.Type);
        BuildVTable(type);
        foreach (MethodDesc method in type.Methods.Where(m => !m.IsGeneric))
            RequireMethod(method);
        BuildInterfaceMap(type);
    }

    // ---- Interfaces ---------------------------------------------------------------------------

    /// <summary>The instance methods of an interface, in declaration order: their index is the slot of interface calls.</summary>
    public static List<MethodDesc> InterfaceMethods(TypeDesc interfaceType) =>
        interfaceType.Methods.Where(m => !m.IsStatic).ToList();

    public static int InterfaceSlot(MethodDesc method) =>
        InterfaceMethods(method.Owner).FindIndex(m => m.Handle == method.Handle);

    /// <summary>Every interface a type implements: declared by it, its base types, and inherited by those interfaces.</summary>
    public static List<TypeDesc> AllInterfaces(TypeDesc type)
    {
        var result = new List<TypeDesc>();
        void Add(TypeDesc i)
        {
            if (result.Contains(i))
                return;
            result.Add(i);
            foreach (TypeDesc inherited in i.DeclaredInterfaces)
                Add(inherited);
        }
        foreach (TypeDesc t in type.BaseTypesAndSelf().Reverse())
            foreach (TypeDesc i in t.DeclaredInterfaces)
                Add(i);
        return result;
    }

    private void BuildInterfaceMap(TypeDesc type)
    {
        if (_interfaceMaps.ContainsKey(type) || type.ContainsGenericParameters)
            return;
        var map = new List<(TypeDesc, List<MethodDesc?>)>();
        _interfaceMaps[type] = map;
        foreach (TypeDesc interfaceType in AllInterfaces(type))
        {
            RequireType(interfaceType);
            var methods = new List<MethodDesc?>();
            if (!type.IsInterface && !type.IsAbstract)
            {
                foreach (MethodDesc method in InterfaceMethods(interfaceType))
                {
                    MethodDesc? implementation = InterfaceImplementation(type, method);
                    if (implementation != null && !implementation.IsAbstract)
                    {
                        RequireMethod(implementation);
                        if (implementation.Owner.IsValueType)
                            _unboxingStubs.Add(implementation);
                    }
                    methods.Add(implementation);
                }
            }
            map.Add((interfaceType, methods));
        }
    }

    /// <summary>
    /// The method an interface call runs on an object of exactly <paramref name="type"/>: an explicit
    /// implementation (MethodImpl), else the most derived public method with the same name and
    /// signature (and its override), else the interface's default implementation.
    /// </summary>
    public MethodDesc? InterfaceImplementation(TypeDesc type, MethodDesc interfaceMethod)
    {
        foreach (TypeDesc t in type.BaseTypesAndSelf())
        {
            var reader = t.Module!.Reader;
            foreach (var handle in reader.GetTypeDefinition(t.Handle).GetMethodImplementations())
            {
                var implementation = reader.GetMethodImplementation(handle);
                MethodDesc declaration = Context.ResolveMethod(t.Module, implementation.MethodDeclaration, new GenericContext(t.TypeArguments, []));
                if (declaration.Owner != interfaceMethod.Owner || declaration.Handle != interfaceMethod.Handle)
                    continue;
                MethodDesc body = Context.ResolveMethod(t.Module, implementation.MethodBody, new GenericContext(t.TypeArguments, []));
                return t.Methods.First(m => m.Handle == body.Handle);
            }
        }
        foreach (TypeDesc t in type.BaseTypesAndSelf())
        {
            foreach (MethodDesc candidate in t.Methods)
            {
                if (candidate.IsStatic || candidate.Name != interfaceMethod.Name || candidate.IsGeneric != interfaceMethod.IsGeneric ||
                    (candidate.Attributes & System.Reflection.MethodAttributes.MemberAccessMask) != System.Reflection.MethodAttributes.Public ||
                    candidate.ReturnType != interfaceMethod.ReturnType || !candidate.ParameterTypes.SequenceEqual(interfaceMethod.ParameterTypes))
                    continue;
                return candidate.IsVirtual ? Implementation(type, candidate) ?? candidate : candidate;
            }
        }
        return interfaceMethod.HasBody ? interfaceMethod : null;
    }

    /// <summary>Queues a method for compilation (a generic one only with its type arguments).</summary>
    public void RequireMethod(MethodDesc method)
    {
        if (method.IsOpen)
            return;
        RequireType(method.Owner);
        if (_requested.Add(method))
            _pending.Enqueue(method);
    }

    /// <summary>Name of the type info of a type used by the code (arrays and instantiations are then emitted).</summary>
    public string TypeInfo(TypeDesc type)
    {
        if (type.IsArray)
            UseArrayType(type);
        RequireType(type);
        return Names.TypeInfo(type);
    }

    // ---- Types --------------------------------------------------------------------------------

    /// <summary>Has a C struct of its own (classes and structs; not primitives, enums or interfaces).</summary>
    public bool HasStruct(TypeDesc type) =>
        type.IsDefinition && !type.IsPrimitive && !type.IsEnum && !type.IsInterface;

    /// <summary>The C type a value of this type is stored as (fields, locals, parameters).</summary>
    public string CType(TypeDesc type)
    {
        if (type.IsGenericParameter)
            throw new TranslationException($"Generic parameter {type} was not substituted.");
        RequireType(type);
        if (type.IsByRef || type.IsPointer)
            return type.ElementType!.IsVoid ? "void*" : CType(type.ElementType!) + "*";
        if (type.IsArray)
            return "MArray*";
        if (type.IsEnum)
            return CType(type.EnumUnderlyingType);
        if (type.IsPrimitive)
        {
            return type.Primitive switch
            {
                PrimitiveKind.Void => "void",
                PrimitiveKind.Boolean => "bool",
                PrimitiveKind.Char => "uint16_t",
                PrimitiveKind.I1 => "int8_t",
                PrimitiveKind.U1 => "uint8_t",
                PrimitiveKind.I2 => "int16_t",
                PrimitiveKind.U2 => "uint16_t",
                PrimitiveKind.I4 => "int32_t",
                PrimitiveKind.U4 => "uint32_t",
                PrimitiveKind.I8 => "int64_t",
                PrimitiveKind.U8 => "uint64_t",
                PrimitiveKind.I => "intptr_t",
                PrimitiveKind.U => "uintptr_t",
                PrimitiveKind.R4 => "float",
                _ => "double",
            };
        }
        if (type.IsInterface)
            return "MObject*";
        return type.IsValueType ? Names.Type(type) : Names.Type(type) + "*";
    }

    /// <summary>Instance fields in layout order: base classes first.</summary>
    public IEnumerable<FieldDesc> InstanceFields(TypeDesc type)
    {
        IEnumerable<TypeDesc> chain = type.IsValueType ? [type] : type.BaseTypesAndSelf().Reverse();
        return chain.SelectMany(t => t.Fields.Where(f => !f.IsStatic));
    }

    /// <summary>Whether instances can point to other objects (the collector must scan them).</summary>
    public bool ContainsReferences(TypeDesc type) => ContainsReferences(type, new HashSet<TypeDesc>());

    private bool ContainsReferences(TypeDesc type, HashSet<TypeDesc> visiting)
    {
        if (type.IsArray || type.IsByRef || type.IsInterface)
            return true;
        if (type.IsPointer || type.IsPrimitive || type.IsEnum)
            return false;
        if (type.IsReferenceType && type != Context.ObjectType && !type.IsDefinition)
            return true;
        if (!visiting.Add(type))
            return false;
        foreach (FieldDesc field in InstanceFields(type))
        {
            TypeDesc fieldType = field.Type;
            if (fieldType.IsReferenceType || fieldType.IsByRef || (fieldType.IsValueType && ContainsReferences(fieldType, visiting)))
                return true;
        }
        return false;
    }

    private void WriteTypeDeclarations(StringBuilder c)
    {
        c.Append("/* ---- Types ---- */\n\n");
        foreach (TypeDesc type in _types.Where(HasStruct))
            c.Append($"typedef struct {Names.Type(type)} {Names.Type(type)};\n");
        c.Append('\n');
    }

    private void WriteStructs(StringBuilder c)
    {
        // Structs containing other structs by value must come after them.
        var written = new HashSet<TypeDesc>();
        void Write(TypeDesc type)
        {
            if (!written.Add(type))
                return;
            foreach (FieldDesc field in InstanceFields(type))
            {
                if (field.Type.IsValueType && HasStruct(field.Type))
                    Write(field.Type);
            }
            if (type.IsExplicitLayout && InstanceFields(type).Any())
                throw new TranslationException($"{type}: explicit struct layouts are not supported yet.");

            c.Append($"struct {Names.Type(type)} {{\n");
            if (type.IsReferenceType)
                c.Append("    MObject header;\n");
            int fieldCount = 0;
            foreach (FieldDesc field in InstanceFields(type))
            {
                c.Append($"    {CType(field.Type)} {Names.Field(field)};\n");
                fieldCount++;
            }
            if (type.IsValueType && fieldCount == 0)
            {
                // C structs cannot be empty; StructLayout(Size = n) types (array initializer data) keep their size.
                int size = Math.Max(1, type.ExplicitSize);
                c.Append($"    uint8_t _data[{size}];\n");
            }
            c.Append("};\n\n");
        }
        foreach (TypeDesc type in _types.Where(HasStruct))
            Write(type);
    }

    private void WriteTypeInfoDeclarations(StringBuilder c)
    {
        foreach (TypeDesc type in _types)
            c.Append($"extern const MType {Names.TypeInfo(type)};\n");
        foreach (TypeDesc array in _arrayTypes)
            c.Append($"extern const MType {Names.TypeInfo(array)};\n");
        c.Append('\n');
    }

    // ---- VTables ------------------------------------------------------------------------------

    /// <summary>Virtual method slots of a class or struct: inherited ones, overridden in place, then new ones.</summary>
    public IReadOnlyList<MethodDesc?> VTable(TypeDesc type)
    {
        if (type.IsArray)
            return VTable(Context.ArrayType);
        return _vtables.TryGetValue(type, out List<MethodDesc?>? slots) ? slots : BuildVTable(type);
    }

    private List<MethodDesc?> BuildVTable(TypeDesc type)
    {
        if (_vtables.TryGetValue(type, out List<MethodDesc?>? existing))
            return existing;
        var slots = type.BaseType is { } baseType ? new List<MethodDesc?>(BuildVTable(baseType)) : new List<MethodDesc?>();
        if (!type.IsInterface)
        {
            foreach (MethodDesc method in type.Methods.Where(m => m.IsVirtual && !m.IsGeneric))
            {
                int slot = -1;
                if (!method.IsNewSlot)
                {
                    for (int i = slots.Count - 1; i >= 0; i--)
                    {
                        MethodDesc? inherited = slots[i];
                        if (inherited != null && inherited.Name == method.Name && inherited.SignatureEquals(method))
                        {
                            slot = i;
                            break;
                        }
                    }
                }
                if (slot < 0)
                {
                    slot = slots.Count;
                    slots.Add(null);
                }
                slots[slot] = method;
                method.VTableSlot = slot;
            }
        }
        _vtables[type] = slots;
        return slots;
    }

    /// <summary>The method a virtual call to <paramref name="method"/> runs on an object of exactly <paramref name="type"/>.</summary>
    public MethodDesc? Implementation(TypeDesc type, MethodDesc method)
    {
        if (method.VTableSlot < 0)
            BuildVTable(method.Owner);
        IReadOnlyList<MethodDesc?> slots = VTable(type);
        return method.VTableSlot >= 0 && method.VTableSlot < slots.Count ? slots[method.VTableSlot] : null;
    }

    // ---- Statics and class initialization -----------------------------------------------------

    public MethodDesc? StaticConstructor(TypeDesc type) =>
        type.IsDefinition ? type.Methods.FirstOrDefault(m => m.IsStaticConstructor) : null;

    private void WriteStatics(StringBuilder c)
    {
        c.Append("/* ---- Static fields ---- */\n\n");
        foreach (TypeDesc type in _types)
        {
            foreach (FieldDesc field in type.Fields.Where(f => f.IsStatic && !f.IsLiteral && !f.HasRva))
                c.Append($"{CType(field.Type)} {Names.StaticField(field)};\n");
        }
        c.Append('\n');
    }

    private void WriteClassInits(StringBuilder c)
    {
        c.Append("/* ---- Static constructors run once, on first use ---- */\n\n");
        foreach (TypeDesc type in _types)
        {
            if (StaticConstructor(type) is not { } cctor)
                continue;
            string check = Names.ClassInit(type);
            c.Append($"static bool {check}_done;\n");
            c.Append($"void {check}(void)\n{{\n    if ({check}_done)\n        return;\n");
            c.Append($"    {check}_done = true;\n    {Names.Method(cctor)}();\n}}\n\n");
        }
    }

    /// <summary>Statement running the type's static constructor if it has not run yet (or "").</summary>
    public string ClassInitCall(TypeDesc type) =>
        StaticConstructor(type) != null ? Names.ClassInit(type) + "();" : "";

    // ---- Prototypes ---------------------------------------------------------------------------

    public string Prototype(MethodDesc method, string? nameOverride = null)
    {
        var parameters = new List<string>();
        if (!method.IsStatic)
            parameters.Add(ThisCType(method.Owner) + " a0");
        for (int i = 0; i < method.ParameterTypes.Count; i++)
            parameters.Add($"{CType(method.ParameterTypes[i])} a{i + (method.IsStatic ? 0 : 1)}");
        return $"{CType(method.ReturnType)} {nameOverride ?? Names.Method(method)}({(parameters.Count == 0 ? "void" : string.Join(", ", parameters))})";
    }

    /// <summary>Type of "this": the object pointer, or a pointer to the value for structs.</summary>
    public string ThisCType(TypeDesc owner)
    {
        if (owner.IsValueType)
            return CType(owner) + "*";
        return owner.IsInterface ? "MObject*" : CType(owner);
    }

    private void WritePrototypes(StringBuilder c)
    {
        c.Append("/* ---- Methods (internal calls are implemented by Engine/Runtime) ---- */\n\n");
        foreach (MethodDesc method in _methods)
            c.Append(Prototype(method)).Append(";\n");
        foreach (TypeDesc type in _types)
        {
            if (StaticConstructor(type) != null)
                c.Append($"void {Names.ClassInit(type)}(void);\n");
        }
        c.Append('\n');
    }

    // ---- Type infos and vtables ---------------------------------------------------------------

    public void UseArrayType(TypeDesc arrayType)
    {
        if (!_arrayTypes.Add(arrayType))
            return;
        if (arrayType.ElementType!.IsArray)
            UseArrayType(arrayType.ElementType);
        RequireType(arrayType.ElementType);
        BuildArrayInterfaceMap(arrayType);
    }

    /// <summary>
    /// T[] implements IList&lt;T&gt;, IReadOnlyList&lt;T&gt; (and the collections and enumerables they
    /// extend) through the corlib's SZArrayHelper&lt;T&gt;, whose static methods take the array first.
    /// </summary>
    private void BuildArrayInterfaceMap(TypeDesc arrayType)
    {
        TypeDesc element = arrayType.ElementType!;
        if (element.IsPointer || element.IsByRef || element.ContainsGenericParameters || !HasCoreType("System", "SZArrayHelper`1"))
            return;
        TypeDesc helper = Context.Instantiate(Context.CoreType("System", "SZArrayHelper`1"), [element]);
        RequireType(helper);
        var map = new List<(TypeDesc, List<MethodDesc?>)>();
        _interfaceMaps[arrayType] = map;
        var roots = new[] { "IList`1", "IReadOnlyList`1" }
            .Select(name => Context.Instantiate(Context.CoreType("System.Collections.Generic", name), [element]));
        var interfaces = new List<TypeDesc>();
        void Add(TypeDesc i)
        {
            if (interfaces.Contains(i))
                return;
            interfaces.Add(i);
            foreach (TypeDesc inherited in i.DeclaredInterfaces)
                Add(inherited);
        }
        foreach (TypeDesc root in roots)
            Add(root);
        foreach (TypeDesc interfaceType in interfaces)
        {
            RequireType(interfaceType);
            var methods = new List<MethodDesc?>();
            foreach (MethodDesc method in InterfaceMethods(interfaceType))
            {
                MethodDesc? implementation = helper.Methods.FirstOrDefault(m => m.IsStatic && m.Name == method.Name &&
                                                                                m.ParameterTypes.Count == method.ParameterTypes.Count + 1);
                if (implementation != null)
                    RequireMethod(implementation);
                methods.Add(implementation);
            }
            map.Add((interfaceType, methods));
        }
    }

    private bool HasCoreType(string ns, string name)
    {
        try
        {
            Context.CoreType(ns, name);
            return true;
        }
        catch (TranslationException)
        {
            return false;
        }
    }

    private void WriteVTablesAndTypeInfos(StringBuilder c)
    {
        c.Append("/* ---- Type infos and vtables ---- */\n\n");
        c.Append("static void m_abstract_method(void)\n{\n    m_throw_named(\"System.EntryPointNotFoundException\", \"An abstract method was called.\");\n}\n\n");

        foreach (TypeDesc type in _types)
        {
            IReadOnlyList<MethodDesc?> slots = type.IsInterface ? [] : VTable(type);
            string vtable = "NULL";
            if (slots.Count > 0)
            {
                vtable = Names.VTable(type);
                c.Append($"static void* const {vtable}[] = {{\n");
                foreach (MethodDesc? slot in slots)
                    c.Append($"    (void*){VTableEntry(type, slot)},\n");
                c.Append("};\n");
            }

            var flags = new List<string>();
            if (type.IsValueType) flags.Add("M_TYPE_VALUE_TYPE");
            if (type.IsInterface) flags.Add("M_TYPE_INTERFACE");
            if (type.IsAbstract) flags.Add("M_TYPE_ABSTRACT");
            if (!ContainsReferences(type)) flags.Add("M_TYPE_NO_REFERENCES");

            string size = type.IsInterface || type.IsVoid ? "0" : type.IsValueType ? $"sizeof({CType(type)})" : $"sizeof({Names.Type(type)})";
            TypeDesc? baseType = type.BaseType;
            string baseInfo = baseType != null ? "&" + Names.TypeInfo(baseType) : "NULL";

            string interfaces = WriteInterfaceMap(c, type);
            var map = _interfaceMaps.GetValueOrDefault(type) ?? [];
            string enumInfo = type.IsEnum ? WriteEnumInfo(c, type) : "NULL";
            c.Append($"const MType {Names.TypeInfo(type)} = {{ {CString(type.FullName)}, {baseInfo}, ");
            c.Append($"{(flags.Count > 0 ? string.Join(" | ", flags) : "0")}, {size}, NULL, 0, {vtable}, {slots.Count}, {interfaces}, {map.Count}, {enumInfo} }};\n\n");
        }

        foreach (TypeDesc array in _arrayTypes)
        {
            TypeDesc element = array.ElementType!;
            int slots = VTable(Context.ArrayType).Count;
            string vtable = slots > 0 ? Names.VTable(Context.ArrayType) : "NULL";
            string interfaces = WriteInterfaceMap(c, array);
            int interfaceCount = _interfaceMaps.GetValueOrDefault(array)?.Count ?? 0;
            c.Append($"const MType {Names.TypeInfo(array)} = {{ {CString(array.FullName)}, &{Names.TypeInfo(Context.ArrayType)}, ");
            c.Append($"M_TYPE_ARRAY, sizeof(MArray), &{Names.TypeInfo(element)}, sizeof({CType(element)}), {vtable}, {slots}, {interfaces}, {interfaceCount}, NULL }};\n");
        }
        c.Append('\n');
    }

    /// <summary>The type's interface map (interfaces and their implementations), or "NULL".</summary>
    private string WriteInterfaceMap(StringBuilder c, TypeDesc type)
    {
        var map = _interfaceMaps.GetValueOrDefault(type) ?? [];
        if (map.Count == 0)
            return "NULL";
        string mapName = Names.Type(type) + "__interfaces";
        for (int i = 0; i < map.Count; i++)
        {
            if (map[i].Methods.Count == 0)
                continue;
            c.Append($"static void* const {mapName}_{i}[] = {{ ");
            foreach (MethodDesc? method in map[i].Methods)
                c.Append($"(void*){(type.IsArray ? method != null ? Names.Method(method) : "m_abstract_method" : VTableEntry(type, method))}, ");
            c.Append("};\n");
        }
        c.Append($"static const MInterfaceMap {mapName}[] = {{\n");
        for (int i = 0; i < map.Count; i++)
            c.Append($"    {{ &{Names.TypeInfo(map[i].Interface)}, {(map[i].Methods.Count > 0 ? $"{mapName}_{i}" : "NULL")} }},\n");
        c.Append("};\n");
        return mapName;
    }

    /// <summary>The constants of an enum (names and values) for Enum.ToString; returns the MEnumInfo's address.</summary>
    private string WriteEnumInfo(StringBuilder c, TypeDesc type)
    {
        var reader = type.Module!.Reader;
        var constants = new List<(string Name, ulong Bits)>();
        foreach (FieldDesc field in type.Fields.Where(f => f.IsStatic && f.IsLiteral))
        {
            var definition = reader.GetFieldDefinition(field.Handle);
            var constant = reader.GetConstant(definition.GetDefaultValue());
            var blob = reader.GetBlobReader(constant.Value);
            ulong bits = constant.TypeCode switch
            {
                System.Reflection.Metadata.ConstantTypeCode.SByte => (ulong)(long)blob.ReadSByte(),
                System.Reflection.Metadata.ConstantTypeCode.Byte => blob.ReadByte(),
                System.Reflection.Metadata.ConstantTypeCode.Int16 => (ulong)(long)blob.ReadInt16(),
                System.Reflection.Metadata.ConstantTypeCode.UInt16 => blob.ReadUInt16(),
                System.Reflection.Metadata.ConstantTypeCode.Int32 => (ulong)(long)blob.ReadInt32(),
                System.Reflection.Metadata.ConstantTypeCode.UInt32 => blob.ReadUInt32(),
                System.Reflection.Metadata.ConstantTypeCode.Int64 => (ulong)blob.ReadInt64(),
                System.Reflection.Metadata.ConstantTypeCode.UInt64 => blob.ReadUInt64(),
                System.Reflection.Metadata.ConstantTypeCode.Char => blob.ReadChar(),
                System.Reflection.Metadata.ConstantTypeCode.Boolean => blob.ReadBoolean() ? 1UL : 0UL,
                _ => 0,
            };
            constants.Add((field.Name, bits));
        }
        bool isFlags = reader.GetTypeDefinition(type.Handle).GetCustomAttributes().Any(handle =>
        {
            var attribute = reader.GetCustomAttribute(handle);
            EntityHandle ctor = attribute.Constructor;
            EntityHandle parent = ctor.Kind == HandleKind.MemberReference
                ? reader.GetMemberReference((MemberReferenceHandle)ctor).Parent
                : reader.GetMethodDefinition((MethodDefinitionHandle)ctor).GetDeclaringType();
            return Context.ResolveType(type.Module, parent).FullName == "System.FlagsAttribute";
        });
        bool isSigned = type.EnumUnderlyingType.Primitive is PrimitiveKind.I1 or PrimitiveKind.I2 or PrimitiveKind.I4 or PrimitiveKind.I8;
        string name = Names.Type(type) + "__enum";
        if (constants.Count > 0)
        {
            c.Append($"static const char* const {name}_names[] = {{ {string.Join(", ", constants.Select(k => CString(k.Name)))} }};\n");
            c.Append($"static const uint64_t {name}_values[] = {{ {string.Join(", ", constants.Select(k => $"UINT64_C({k.Bits})"))} }};\n");
        }
        string names = constants.Count > 0 ? $"{name}_names" : "NULL", values = constants.Count > 0 ? $"{name}_values" : "NULL";
        c.Append($"static const MEnumInfo {name} = {{ {constants.Count}, {(isFlags ? "true" : "false")}, {(isSigned ? "true" : "false")}, {names}, {values} }};\n");
        return "&" + name;
    }

    private string VTableEntry(TypeDesc type, MethodDesc? method)
    {
        if (method == null || method.IsAbstract || (!method.HasBody && !method.IsInternalCall && !IsDelegate(method.Owner)))
            return "m_abstract_method";
        // Boxed structs hold the value after the object header: their overrides go through a stub.
        return method.Owner.IsValueType ? UnboxingStubName(method) : Names.Method(method);
    }

    public string UnboxingStubName(MethodDesc method)
    {
        _unboxingStubs.Add(method);
        return Names.Method(method) + "__unbox";
    }

    private void WriteUnboxingStubs(StringBuilder c)
    {
        c.Append("/* ---- Virtual methods of structs, called on boxed values ---- */\n\n");
        foreach (TypeDesc type in _types.Where(t => t.IsValueType))
        {
            foreach (MethodDesc method in type.Methods.Where(m => !m.IsStatic && m.HasBody && !m.IsGeneric && _requested.Contains(m) &&
                                                                 (m.IsVirtual || _unboxingStubs.Contains(m))))
            {
                var parameters = new List<string> { "MObject* self" };
                var arguments = new List<string> { $"({ThisCType(type)})M_BOX_DATA(self)" };
                for (int i = 0; i < method.ParameterTypes.Count; i++)
                {
                    parameters.Add($"{CType(method.ParameterTypes[i])} a{i + 1}");
                    arguments.Add($"a{i + 1}");
                }
                string call = $"{Names.Method(method)}({string.Join(", ", arguments)})";
                c.Append($"static {CType(method.ReturnType)} {UnboxingStubName(method)}({string.Join(", ", parameters)})\n{{\n");
                c.Append(method.ReturnType.IsVoid ? $"    {call};\n" : $"    return {call};\n").Append("}\n\n");
            }
        }
    }

    // ---- Delegates ----------------------------------------------------------------------------

    public bool IsDelegate(TypeDesc type) =>
        type.IsDefinition && type.BaseType is { } baseType && baseType.FullName == "System.MulticastDelegate";

    /// <summary>C name of a field of System.Delegate (_target, _methodPtr, _isStatic, _invocationList).</summary>
    public string DelegateField(string name) =>
        Names.Field(Context.CoreType("System", "Delegate").Fields.First(f => f.Name == name));

    /// <summary>
    /// The runtime-implemented members of a delegate type. Invoke calls each delegate of the
    /// invocation list (Delegate.Combine), or the function with the target as this (none for a
    /// static method).
    /// </summary>
    private string DelegateMethod(MethodDesc method)
    {
        string self = $"(({CType(method.Owner)})a0)";
        var c = new StringBuilder(Prototype(method)).Append("\n{\n");
        if (method.IsConstructor)
        {
            c.Append($"    {self}->{DelegateField("_target")} = ({CType(Context.ObjectType)})a1;\n");
            c.Append($"    {self}->{DelegateField("_methodPtr")} = a2;\n");
            return c.Append("}\n").ToString();
        }

        var parameters = method.ParameterTypes.Select((t, i) => (Type: CType(t), Name: $"a{i + 1}")).ToList();
        string arguments = string.Join(", ", parameters.Select(p => p.Name));
        bool returns = !method.ReturnType.IsVoid;
        string list = $"{self}->{DelegateField("_invocationList")}";
        c.Append($"    if ({list} != NULL) {{\n");
        if (returns)
            c.Append($"        {CType(method.ReturnType)} result;\n        memset((void*)&result, 0, sizeof result);\n");
        c.Append($"        for (int32_t i = 0; i < ((MArray*){list})->length; i++)\n");
        string call = $"{Names.Method(method)}({string.Join(", ", new[] { $"({CType(method.Owner)})((MObject**)M_ARRAY_DATA({list}))[i]" }.Concat(parameters.Select(p => p.Name)))})";
        c.Append(returns ? $"            result = {call};\n        return result;\n" : $"            {call};\n        return;\n");
        c.Append("    }\n");
        string staticType = $"{CType(method.ReturnType)} (*)({(parameters.Count == 0 ? "void" : string.Join(", ", parameters.Select(p => p.Type)))})";
        string instanceType = $"{CType(method.ReturnType)} (*)({string.Join(", ", new[] { "void*" }.Concat(parameters.Select(p => p.Type)))})";
        string function = $"{self}->{DelegateField("_methodPtr")}";
        string ret = returns ? "return " : "";
        c.Append($"    if ({self}->{DelegateField("_isStatic")})\n");
        c.Append($"        {ret}(({staticType}){function})({arguments});\n    else\n");
        c.Append($"        {ret}(({instanceType}){function})({string.Join(", ", new[] { $"(void*){self}->{DelegateField("_target")}" }.Concat(parameters.Select(p => p.Name)))});\n");
        return c.Append("}\n").ToString();
    }

    // ---- Exceptions raised by the runtime -----------------------------------------------------

    /// <summary>m_new_exception: the runtime's errors (null reference, bad cast...) as corlib exception objects.</summary>
    private void WriteExceptionFactory(StringBuilder c)
    {
        TypeDesc exception = Context.CoreType("System", "Exception");
        c.Append("MObject* m_new_exception(const char* typeName, const char* message)\n{\n");
        c.Append("    MString* text = m_string_from_utf8(message);\n    MObject* e;\n");
        IEnumerable<TypeDesc> types = _types.Where(t => t.Module == Context.CoreLib && !t.IsInstantiation && t.IsSubclassOf(exception) && !t.IsAbstract)
            .OrderBy(t => t == exception ? 1 : 0);
        foreach (TypeDesc type in types)
        {
            MethodDesc? constructor = type.Methods.FirstOrDefault(m => m.IsConstructor && m.ParameterTypes.Count == 1 &&
                                                                       m.ParameterTypes[0] == Context.StringType);
            if (constructor == null)
                continue;
            string test = type == exception ? "" : $"if (strcmp(typeName, {CString(type.FullName)}) == 0) ";
            c.Append($"    {test}{{\n        e = m_new_object(&{Names.TypeInfo(type)});\n");
            c.Append($"        {Names.Method(constructor)}(({CType(type)})e, (System_String*)text);\n        return e;\n    }}\n");
        }
        c.Append("}\n\n");
    }

    // ---- Literals and data --------------------------------------------------------------------

    /// <summary>A static string object for a literal (identical literals share one).</summary>
    public string StringLiteral(string value)
    {
        if (_strings.TryGetValue(value, out string? name))
            return name;
        name = $"m_str_{_strings.Count}";
        _strings[value] = name;
        _stringDefinitions.Append($"static struct {{ MObject header; int32_t length; uint16_t chars[{value.Length + 1}]; }} {name} = {{ {{ &System_String__type }}, {value.Length}, {{ ");
        foreach (char ch in value)
            _stringDefinitions.Append((int)ch).Append(", ");
        _stringDefinitions.Append($"0 }} }}; /* {CommentSafe(value)} */\n");
        return name;
    }

    /// <summary>Constant data of a field with an RVA (array initializers), as a static byte array.</summary>
    public (string Name, int Size) RvaData(FieldDesc field)
    {
        if (_rvaData.TryGetValue(field, out var data))
            return data;
        int size = SizeOf(field.Type);
        string name = $"m_data_{_rvaData.Count}";
        ReadOnlySpan<byte> bytes = field.GetRvaData(size);
        _rvaDefinitions.Append($"static alignas(8) uint8_t {name}[{Math.Max(size, 1)}] = {{ ");
        foreach (byte b in bytes)
            _rvaDefinitions.Append(b).Append(", ");
        _rvaDefinitions.Append("};\n");
        data = (name, size);
        _rvaData[field] = data;
        return data;
    }

    /// <summary>Size in bytes of primitive types and StructLayout(Size = n) structs (constant data only).</summary>
    private int SizeOf(TypeDesc type)
    {
        if (type.IsEnum)
            return SizeOf(type.EnumUnderlyingType);
        return type.Primitive switch
        {
            PrimitiveKind.Boolean or PrimitiveKind.I1 or PrimitiveKind.U1 => 1,
            PrimitiveKind.Char or PrimitiveKind.I2 or PrimitiveKind.U2 => 2,
            PrimitiveKind.I4 or PrimitiveKind.U4 or PrimitiveKind.R4 => 4,
            PrimitiveKind.I8 or PrimitiveKind.U8 or PrimitiveKind.R8 => 8,
            _ => type.ExplicitSize > 0
                ? type.ExplicitSize
                : throw new TranslationException($"Constant data of type {type} is not supported."),
        };
    }

    public static string CString(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (byte b in Encoding.UTF8.GetBytes(value))
        {
            if (b is (byte)'"' or (byte)'\\')
                builder.Append('\\').Append((char)b);
            else if (b < 0x20 || b >= 0x7F)
                builder.Append($"\\{Convert.ToString(b, 8).PadLeft(3, '0')}");
            else
                builder.Append((char)b);
        }
        return builder.Append('"').ToString();
    }

    private static string CommentSafe(string value)
    {
        string text = value.Length > 40 ? value[..40] + "..." : value;
        var builder = new StringBuilder();
        foreach (char ch in text)
            builder.Append(ch is >= ' ' and < '\x7f' ? ch : '?');
        return builder.ToString().Replace("*/", "*\\/");
    }

    // ---- Entry point --------------------------------------------------------------------------

    private MethodDesc FindEntryPoint(string entryPoint)
    {
        int dot = entryPoint.LastIndexOf('.');
        if (dot <= 0)
            throw new TranslationException($"Entry point '{entryPoint}' must be Namespace.Type.Method.");
        string typeName = entryPoint[..dot], methodName = entryPoint[(dot + 1)..];
        TypeDesc type = _types.FirstOrDefault(t => t.FullName == typeName)
                        ?? throw new TranslationException($"Entry point type {typeName} not found.");
        return type.Methods.FirstOrDefault(m => m.Name == methodName && m.IsStatic)
               ?? throw new TranslationException($"Static method {entryPoint} not found.");
    }

    private void WriteMain(StringBuilder c, MethodDesc entry)
    {
        bool takesArgs = entry.ParameterTypes.Count == 1;
        bool returnsInt = entry.ReturnType.Primitive == PrimitiveKind.I4;
        c.Append("int main(int argc, char** argv)\n{\n    m_init();\n");
        c.Append("    (void)argc;\n    (void)argv;\n");
        if (ClassInitCall(entry.Owner) is { Length: > 0 } init)
            c.Append($"    {init}\n");
        string args = takesArgs ? $"m_make_args(argc, argv, &{Names.TypeInfo(Context.MakeArray(Context.StringType))})" : "";
        string call = $"{Names.Method(entry)}({args})";
        c.Append(returnsInt ? $"    int result = {call};\n" : $"    {call};\n    int result = 0;\n");
        c.Append("    fflush(stdout);\n    return result;\n}\n");
    }

    public static string FloatLiteral(double value, bool single)
    {
        if (double.IsNaN(value) || double.IsInfinity(value) || (value == 0 && double.IsNegative(value)))
        {
            return single
                ? $"m_r4_bits(0x{BitConverter.SingleToUInt32Bits((float)value):x8}u)"
                : $"m_r8_bits(0x{BitConverter.DoubleToUInt64Bits(value):x16}ull)";
        }
        string text = single ? ((float)value).ToString("R", CultureInfo.InvariantCulture) : value.ToString("R", CultureInfo.InvariantCulture);
        if (!text.Contains('.') && !text.Contains('E'))
            text += ".0";
        return single ? text + "f" : text;
    }
