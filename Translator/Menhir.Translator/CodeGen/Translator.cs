using System.Globalization;
using System.Text;
using Menhir.Translator.TypeSystem;

namespace Menhir.Translator.CodeGen;

/// <summary>
/// Translates loaded assemblies into one C file for Engine/Runtime: type layouts, type infos and
/// vtables, statics, string literals, and every method body (see <see cref="MethodCompiler"/>).
/// </summary>
public sealed class Il2cTranslator
{
    private readonly Dictionary<TypeDesc, List<MethodDesc?>> _vtables = new();
    private readonly Dictionary<string, string> _strings = new();
    private readonly StringBuilder _stringDefinitions = new();
    private readonly Dictionary<FieldDesc, (string Name, int Size)> _rvaData = new();
    private readonly StringBuilder _rvaDefinitions = new();
    private readonly HashSet<TypeDesc> _arrayTypes = new();
    private readonly List<TypeDesc> _types;

    public Il2cTranslator(TypeSystemContext context)
    {
        Context = context;
        _types = context.AllDefinitions
            .Where(t => !t.IsGenericDefinition && !(t.DeclaringType?.IsGenericDefinition ?? false))
            .OrderBy(t => t.Module == context.CoreLib ? 0 : 1)
            .ThenBy(t => t.FullName, StringComparer.Ordinal)
            .ToList();
    }

    public TypeSystemContext Context { get; }
    public CNames Names { get; } = new();

    /// <summary>Problems found while translating, as "method: reason".</summary>
    public List<string> Errors { get; } = new();

    /// <summary>
    /// The whole program as C. <paramref name="entryPoint"/> ("Namespace.Type.Method", a static
    /// method taking nothing or string[] and returning void or int) gets a C main().
    /// </summary>
    public string Translate(string? entryPoint)
    {
        foreach (TypeDesc type in _types)
            BuildVTable(type);

        // Method bodies first: they register the string literals, arrays and data they use.
        var bodies = new StringBuilder();
        foreach (TypeDesc type in _types)
        {
            foreach (MethodDesc method in type.Methods)
            {
                if (!method.HasBody || method.IsGeneric || method.IsInternalCall)
                    continue;
                try
                {
                    bodies.Append(new MethodCompiler(this, method).Compile()).Append('\n');
                }
                catch (TranslationException e)
                {
                    Errors.Add($"{method}: {e.Message}");
                }
            }
        }
        MethodDesc? entry = entryPoint != null ? FindEntryPoint(entryPoint) : null;
        if (entry != null)
            UseArrayType(Context.MakeArray(Context.StringType));
        if (Errors.Count > 0)
            throw new TranslationException("Translation failed:\n  " + string.Join("\n  ", Errors));

        var c = new StringBuilder();
        c.Append("/* Generated by Menhir IL2C. Do not edit. */\n");
        c.Append("#include \"menhir/runtime.h\"\n#include <stdio.h>\n\n");
        WriteTypeDeclarations(c);
        WriteStructs(c);
        WriteTypeInfoDeclarations(c);
        WriteStatics(c);
        WritePrototypes(c);
        c.Append("/* ---- String literals and constant data ---- */\n\n");
        c.Append(_stringDefinitions).Append(_rvaDefinitions).Append('\n');
        WriteUnboxingStubs(c);
        WriteVTablesAndTypeInfos(c);
        WriteClassInits(c);
        c.Append("/* ---- Methods ---- */\n\n").Append(bodies);
        if (entry != null)
            WriteMain(c, entry);
        return c.ToString();
    }

    // ---- Types --------------------------------------------------------------------------------

    /// <summary>Has a C struct of its own (classes and structs; not primitives, enums or interfaces).</summary>
    public bool HasStruct(TypeDesc type) =>
        type.IsDefinition && !type.IsPrimitive && !type.IsEnum && !type.IsInterface;

    /// <summary>The C type a value of this type is stored as (fields, locals, parameters).</summary>
    public string CType(TypeDesc type)
    {
        if (type.IsByRef || type.IsPointer)
            return type.ElementType!.IsVoid ? "void*" : CType(type.ElementType!) + "*";
        if (type.IsArray)
            return "MArray*";
        if (type.IsEnum)
            return CType(type.EnumUnderlyingType);
        if (type.IsPrimitive)
        {
            return type.Primitive switch
            {
                PrimitiveKind.Void => "void",
                PrimitiveKind.Boolean => "bool",
                PrimitiveKind.Char => "uint16_t",
                PrimitiveKind.I1 => "int8_t",
                PrimitiveKind.U1 => "uint8_t",
                PrimitiveKind.I2 => "int16_t",
                PrimitiveKind.U2 => "uint16_t",
                PrimitiveKind.I4 => "int32_t",
                PrimitiveKind.U4 => "uint32_t",
                PrimitiveKind.I8 => "int64_t",
                PrimitiveKind.U8 => "uint64_t",
                PrimitiveKind.I => "intptr_t",
                PrimitiveKind.U => "uintptr_t",
                PrimitiveKind.R4 => "float",
                _ => "double",
            };
        }
        if (type.IsInterface)
            return "MObject*";
        return type.IsValueType ? Names.Type(type) : Names.Type(type) + "*";
    }

    /// <summary>Instance fields in layout order: base classes first.</summary>
    public IEnumerable<FieldDesc> InstanceFields(TypeDesc type)
    {
        IEnumerable<TypeDesc> chain = type.IsValueType ? [type] : type.BaseTypesAndSelf().Reverse();
        return chain.SelectMany(t => t.Fields.Where(f => !f.IsStatic));
    }

    /// <summary>Whether instances can point to other objects (the collector must scan them).</summary>
    public bool ContainsReferences(TypeDesc type) => ContainsReferences(type, new HashSet<TypeDesc>());

    private bool ContainsReferences(TypeDesc type, HashSet<TypeDesc> visiting)
    {
        if (type.IsArray || type.IsByRef || type.IsInterface)
            return true;
        if (type.IsPointer || type.IsPrimitive || type.IsEnum)
            return false;
        if (type.IsReferenceType && type != Context.ObjectType && !type.IsDefinition)
            return true;
        if (!visiting.Add(type))
            return false;
        foreach (FieldDesc field in InstanceFields(type))
        {
            TypeDesc fieldType = field.Type;
            if (fieldType.IsReferenceType || fieldType.IsByRef || (fieldType.IsValueType && ContainsReferences(fieldType, visiting)))
                return true;
        }
        return false;
    }

    private void WriteTypeDeclarations(StringBuilder c)
    {
        c.Append("/* ---- Types ---- */\n\n");
        foreach (TypeDesc type in _types.Where(HasStruct))
            c.Append($"typedef struct {Names.Type(type)} {Names.Type(type)};\n");
        c.Append('\n');
    }

    private void WriteStructs(StringBuilder c)
    {
        // Structs containing other structs by value must come after them.
        var written = new HashSet<TypeDesc>();
        void Write(TypeDesc type)
        {
            if (!written.Add(type))
                return;
            foreach (FieldDesc field in InstanceFields(type))
            {
                if (field.Type.IsValueType && HasStruct(field.Type))
                    Write(field.Type);
            }
            if (type.IsExplicitLayout && InstanceFields(type).Any())
                throw new TranslationException($"{type}: explicit struct layouts are not supported yet.");

            c.Append($"struct {Names.Type(type)} {{\n");
            if (type.IsReferenceType)
                c.Append("    MObject header;\n");
            int fieldCount = 0;
            foreach (FieldDesc field in InstanceFields(type))
            {
                c.Append($"    {CType(field.Type)} {Names.Field(field)};\n");
                fieldCount++;
            }
            if (type.IsValueType && fieldCount == 0)
            {
                // C structs cannot be empty; StructLayout(Size = n) types (array initializer data) keep their size.
                int size = Math.Max(1, type.ExplicitSize);
                c.Append($"    uint8_t _data[{size}];\n");
            }
            c.Append("};\n\n");
        }
        foreach (TypeDesc type in _types.Where(HasStruct))
            Write(type);
    }

    private void WriteTypeInfoDeclarations(StringBuilder c)
    {
        foreach (TypeDesc type in _types)
            c.Append($"extern const MType {Names.TypeInfo(type)};\n");
        foreach (TypeDesc array in _arrayTypes)
            c.Append($"extern const MType {Names.TypeInfo(array)};\n");
        c.Append('\n');
    }

    // ---- VTables ------------------------------------------------------------------------------

    /// <summary>Virtual method slots of a class or struct: inherited ones, overridden in place, then new ones.</summary>
    public IReadOnlyList<MethodDesc?> VTable(TypeDesc type)
    {
        if (type.IsArray)
            return VTable(Context.ArrayType);
        return _vtables.TryGetValue(type, out List<MethodDesc?>? slots) ? slots : BuildVTable(type);
    }

    private List<MethodDesc?> BuildVTable(TypeDesc type)
    {
        if (_vtables.TryGetValue(type, out List<MethodDesc?>? existing))
            return existing;
        var slots = type.BaseType is { } baseType ? new List<MethodDesc?>(BuildVTable(baseType)) : new List<MethodDesc?>();
        if (!type.IsInterface)
        {
            foreach (MethodDesc method in type.Methods.Where(m => m.IsVirtual && !m.IsGeneric))
            {
                int slot = -1;
                if (!method.IsNewSlot)
                {
                    for (int i = slots.Count - 1; i >= 0; i--)
                    {
                        MethodDesc? inherited = slots[i];
                        if (inherited != null && inherited.Name == method.Name && inherited.SignatureEquals(method))
                        {
                            slot = i;
                            break;
                        }
                    }
                }
                if (slot < 0)
                {
                    slot = slots.Count;
                    slots.Add(null);
                }
                slots[slot] = method;
                method.VTableSlot = slot;
            }
        }
        _vtables[type] = slots;
        return slots;
    }

    /// <summary>The method a virtual call to <paramref name="method"/> runs on an object of exactly <paramref name="type"/>.</summary>
    public MethodDesc? Implementation(TypeDesc type, MethodDesc method)
    {
        if (method.VTableSlot < 0)
            BuildVTable(method.Owner);
        IReadOnlyList<MethodDesc?> slots = VTable(type);
        return method.VTableSlot >= 0 && method.VTableSlot < slots.Count ? slots[method.VTableSlot] : null;
    }

    // ---- Statics and class initialization -----------------------------------------------------

    public MethodDesc? StaticConstructor(TypeDesc type) =>
        type.IsDefinition ? type.Methods.FirstOrDefault(m => m.IsStaticConstructor) : null;

    private void WriteStatics(StringBuilder c)
    {
        c.Append("/* ---- Static fields ---- */\n\n");
        foreach (TypeDesc type in _types)
        {
            foreach (FieldDesc field in type.Fields.Where(f => f.IsStatic && !f.IsLiteral && !f.HasRva))
                c.Append($"{CType(field.Type)} {Names.StaticField(field)};\n");
        }
        c.Append('\n');
    }

    private void WriteClassInits(StringBuilder c)
    {
        c.Append("/* ---- Static constructors run once, on first use ---- */\n\n");
        foreach (TypeDesc type in _types)
        {
            if (StaticConstructor(type) is not { } cctor)
                continue;
            string check = Names.ClassInit(type);
            c.Append($"static bool {check}_done;\n");
            c.Append($"void {check}(void)\n{{\n    if ({check}_done)\n        return;\n");
            c.Append($"    {check}_done = true;\n    {Names.Method(cctor)}();\n}}\n\n");
        }
    }

    /// <summary>Statement running the type's static constructor if it has not run yet (or "").</summary>
    public string ClassInitCall(TypeDesc type) =>
        StaticConstructor(type) != null ? Names.ClassInit(type) + "();" : "";

    // ---- Prototypes ---------------------------------------------------------------------------

    public string Prototype(MethodDesc method, string? nameOverride = null)
    {
        var parameters = new List<string>();
        if (!method.IsStatic)
            parameters.Add(ThisCType(method.Owner) + " a0");
        for (int i = 0; i < method.ParameterTypes.Count; i++)
            parameters.Add($"{CType(method.ParameterTypes[i])} a{i + (method.IsStatic ? 0 : 1)}");
        return $"{CType(method.ReturnType)} {nameOverride ?? Names.Method(method)}({(parameters.Count == 0 ? "void" : string.Join(", ", parameters))})";
    }

    /// <summary>Type of "this": the object pointer, or a pointer to the value for structs.</summary>
    public string ThisCType(TypeDesc owner)
    {
        if (owner.IsValueType)
            return CType(owner) + "*";
        return owner.IsInterface ? "MObject*" : CType(owner);
    }

    private void WritePrototypes(StringBuilder c)
    {
        c.Append("/* ---- Methods (internal calls are implemented by Engine/Runtime) ---- */\n\n");
        foreach (TypeDesc type in _types)
        {
            foreach (MethodDesc method in type.Methods)
            {
                if (method.IsGeneric || (!method.HasBody && !method.IsInternalCall))
                    continue;
                c.Append(Prototype(method)).Append(";\n");
            }
            if (StaticConstructor(type) != null)
                c.Append($"void {Names.ClassInit(type)}(void);\n");
        }
        c.Append('\n');
    }

    // ---- Type infos and vtables ---------------------------------------------------------------

    public void UseArrayType(TypeDesc arrayType)
    {
        if (_arrayTypes.Add(arrayType) && arrayType.ElementType!.IsArray)
            UseArrayType(arrayType.ElementType);
    }

    private void WriteVTablesAndTypeInfos(StringBuilder c)
    {
        c.Append("/* ---- Type infos and vtables ---- */\n\n");
        c.Append("static void m_abstract_method(void)\n{\n    m_throw_named(\"System.EntryPointNotFoundException\", \"An abstract method was called.\");\n}\n\n");

        foreach (TypeDesc type in _types)
        {
            IReadOnlyList<MethodDesc?> slots = type.IsInterface ? [] : VTable(type);
            string vtable = "NULL";
            if (slots.Count > 0)
            {
                vtable = Names.VTable(type);
                c.Append($"static void* const {vtable}[] = {{\n");
                foreach (MethodDesc? slot in slots)
                    c.Append($"    (void*){VTableEntry(type, slot)},\n");
                c.Append("};\n");
            }

            var flags = new List<string>();
            if (type.IsValueType) flags.Add("M_TYPE_VALUE_TYPE");
            if (type.IsInterface) flags.Add("M_TYPE_INTERFACE");
            if (type.IsAbstract) flags.Add("M_TYPE_ABSTRACT");
            if (!ContainsReferences(type)) flags.Add("M_TYPE_NO_REFERENCES");

            string size = type.IsInterface || type.IsVoid ? "0" : type.IsValueType ? $"sizeof({CType(type)})" : $"sizeof({Names.Type(type)})";
            TypeDesc? baseType = type.BaseType;
            string baseInfo = baseType != null ? "&" + Names.TypeInfo(baseType) : "NULL";
            c.Append($"const MType {Names.TypeInfo(type)} = {{ {CString(type.FullName)}, {baseInfo}, ");
            c.Append($"{(flags.Count > 0 ? string.Join(" | ", flags) : "0")}, {size}, NULL, 0, {vtable}, {slots.Count} }};\n\n");
        }

        foreach (TypeDesc array in _arrayTypes)
        {
            TypeDesc element = array.ElementType!;
            int slots = VTable(Context.ArrayType).Count;
            string vtable = slots > 0 ? Names.VTable(Context.ArrayType) : "NULL";
            c.Append($"const MType {Names.TypeInfo(array)} = {{ {CString(array.FullName)}, &{Names.TypeInfo(Context.ArrayType)}, ");
            c.Append($"M_TYPE_ARRAY, sizeof(MArray), &{Names.TypeInfo(element)}, sizeof({CType(element)}), {vtable}, {slots} }};\n");
        }
        c.Append('\n');
    }

    private string VTableEntry(TypeDesc type, MethodDesc? method)
    {
        if (method == null || method.IsAbstract || (!method.HasBody && !method.IsInternalCall))
            return "m_abstract_method";
        // Boxed structs hold the value after the object header: their overrides go through a stub.
        return method.Owner.IsValueType ? UnboxingStubName(method) : Names.Method(method);
    }

    private string UnboxingStubName(MethodDesc method) => Names.Method(method) + "__unbox";

    private void WriteUnboxingStubs(StringBuilder c)
    {
        c.Append("/* ---- Virtual methods of structs, called on boxed values ---- */\n\n");
        foreach (TypeDesc type in _types.Where(t => t.IsValueType))
        {
            foreach (MethodDesc method in type.Methods.Where(m => m.IsVirtual && m.HasBody && !m.IsGeneric))
            {
                var parameters = new List<string> { "MObject* self" };
                var arguments = new List<string> { $"({ThisCType(type)})M_BOX_DATA(self)" };
                for (int i = 0; i < method.ParameterTypes.Count; i++)
                {
                    parameters.Add($"{CType(method.ParameterTypes[i])} a{i + 1}");
                    arguments.Add($"a{i + 1}");
                }
                string call = $"{Names.Method(method)}({string.Join(", ", arguments)})";
                c.Append($"static {CType(method.ReturnType)} {UnboxingStubName(method)}({string.Join(", ", parameters)})\n{{\n");
                c.Append(method.ReturnType.IsVoid ? $"    {call};\n" : $"    return {call};\n").Append("}\n\n");
            }
        }
    }

    // ---- Literals and data --------------------------------------------------------------------

    /// <summary>A static string object for a literal (identical literals share one).</summary>
    public string StringLiteral(string value)
    {
        if (_strings.TryGetValue(value, out string? name))
            return name;
        name = $"m_str_{_strings.Count}";
        _strings[value] = name;
        _stringDefinitions.Append($"static struct {{ MObject header; int32_t length; uint16_t chars[{value.Length + 1}]; }} {name} = {{ {{ &System_String__type }}, {value.Length}, {{ ");
        foreach (char ch in value)
            _stringDefinitions.Append((int)ch).Append(", ");
        _stringDefinitions.Append($"0 }} }}; /* {CommentSafe(value)} */\n");
        return name;
    }

    /// <summary>Constant data of a field with an RVA (array initializers), as a static byte array.</summary>
    public (string Name, int Size) RvaData(FieldDesc field)
    {
        if (_rvaData.TryGetValue(field, out var data))
            return data;
        int size = SizeOf(field.Type);
        string name = $"m_data_{_rvaData.Count}";
        ReadOnlySpan<byte> bytes = field.GetRvaData(size);
        _rvaDefinitions.Append($"static alignas(8) uint8_t {name}[{Math.Max(size, 1)}] = {{ ");
        foreach (byte b in bytes)
            _rvaDefinitions.Append(b).Append(", ");
        _rvaDefinitions.Append("};\n");
        data = (name, size);
        _rvaData[field] = data;
        return data;
    }

    /// <summary>Size in bytes of primitive types and StructLayout(Size = n) structs (constant data only).</summary>
    private int SizeOf(TypeDesc type)
    {
        if (type.IsEnum)
            return SizeOf(type.EnumUnderlyingType);
        return type.Primitive switch
        {
            PrimitiveKind.Boolean or PrimitiveKind.I1 or PrimitiveKind.U1 => 1,
            PrimitiveKind.Char or PrimitiveKind.I2 or PrimitiveKind.U2 => 2,
            PrimitiveKind.I4 or PrimitiveKind.U4 or PrimitiveKind.R4 => 4,
            PrimitiveKind.I8 or PrimitiveKind.U8 or PrimitiveKind.R8 => 8,
            _ => type.ExplicitSize > 0
                ? type.ExplicitSize
                : throw new TranslationException($"Constant data of type {type} is not supported."),
        };
    }

    public static string CString(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (byte b in Encoding.UTF8.GetBytes(value))
        {
            if (b is (byte)'"' or (byte)'\\')
                builder.Append('\\').Append((char)b);
            else if (b < 0x20 || b >= 0x7F)
                builder.Append($"\\{Convert.ToString(b, 8).PadLeft(3, '0')}");
            else
                builder.Append((char)b);
        }
        return builder.Append('"').ToString();
    }

    private static string CommentSafe(string value)
    {
        string text = value.Length > 40 ? value[..40] + "..." : value;
        var builder = new StringBuilder();
        foreach (char ch in text)
            builder.Append(ch is >= ' ' and < '\x7f' ? ch : '?');
        return builder.ToString().Replace("*/", "*\\/");
    }

    // ---- Entry point --------------------------------------------------------------------------

    private MethodDesc FindEntryPoint(string entryPoint)
    {
        int dot = entryPoint.LastIndexOf('.');
        if (dot <= 0)
            throw new TranslationException($"Entry point '{entryPoint}' must be Namespace.Type.Method.");
        string typeName = entryPoint[..dot], methodName = entryPoint[(dot + 1)..];
        TypeDesc type = _types.FirstOrDefault(t => t.FullName == typeName)
                        ?? throw new TranslationException($"Entry point type {typeName} not found.");
        return type.Methods.FirstOrDefault(m => m.Name == methodName && m.IsStatic)
               ?? throw new TranslationException($"Static method {entryPoint} not found.");
    }

    private void WriteMain(StringBuilder c, MethodDesc entry)
    {
        bool takesArgs = entry.ParameterTypes.Count == 1;
        bool returnsInt = entry.ReturnType.Primitive == PrimitiveKind.I4;
        c.Append("int main(int argc, char** argv)\n{\n    m_init();\n");
        c.Append("    (void)argc;\n    (void)argv;\n");
        if (ClassInitCall(entry.Owner) is { Length: > 0 } init)
            c.Append($"    {init}\n");
        string args = takesArgs ? $"m_make_args(argc, argv, &{Names.TypeInfo(Context.MakeArray(Context.StringType))})" : "";
        string call = $"{Names.Method(entry)}({args})";
        c.Append(returnsInt ? $"    int result = {call};\n" : $"    {call};\n    int result = 0;\n");
        c.Append("    fflush(stdout);\n    return result;\n}\n");
    }

    public static string FloatLiteral(double value, bool single)
    {
        if (double.IsNaN(value) || double.IsInfinity(value) || (value == 0 && double.IsNegative(value)))
        {
            return single
                ? $"m_r4_bits(0x{BitConverter.SingleToUInt32Bits((float)value):x8}u)"
                : $"m_r8_bits(0x{BitConverter.DoubleToUInt64Bits(value):x16}ull)";
        }
        string text = single ? ((float)value).ToString("R", CultureInfo.InvariantCulture) : value.ToString("R", CultureInfo.InvariantCulture);
        if (!text.Contains('.') && !text.Contains('E'))
            text += ".0";
        return single ? text + "f" : text;
    }
}
