using System.Text;
using System.Text.RegularExpressions;

namespace Menhir.Editor.Scripting;

/// <summary>
/// C++ scripts in the style of Unity (Engine/Scripting/include/menhir.hpp, Docs/Scripting.md): each class
/// deriving from MenhirEngine is a script named after the class, whose public variables of the field types
/// (int, float, bool, MenhirVec2, MenhirPos, MenhirColor, MenhirText, MenhirStyle) are its fields. The
/// compiler gets a generated copy: menhir.hpp, the file itself (#include, so its messages keep the file's
/// lines), then for each class the fields (offsets and defaults) and MENHIR_REGISTER. A .cpp file without
/// such a class is compiled as it is.
/// </summary>
public static partial class CppScriptTransform
{
    /// <summary>The script classes of a C++ file.</summary>
    public static IReadOnlyList<string> ScriptClasses(string source) =>
        ScriptClass().Matches(ScriptTransform.CodeOnly(source)).Select(m => m.Groups["name"].Value).ToList();

    /// <param name="path">The file's full path (the generated copy includes it).</param>
    /// <param name="displayPath">Its path for messages ("Assets/Scripts/Player.cpp").</param>
    public static ScriptTransformResult Transform(string source, string path, string displayPath)
    {
        var diagnostics = new List<ScriptDiagnostic>();
        string code = ScriptTransform.CodeOnly(source);
        void Error(int index, string message)
        {
            (int line, int column) = ScriptTransform.Position(source, index);
            diagnostics.Add(new ScriptDiagnostic(displayPath, line, column, message, true));
        }

        var output = new StringBuilder();
        output.Append($"/* Generated by Menhir from {displayPath}: edit that file instead. */\n");
        output.Append("#include <menhir.hpp>\n");
        AppendScene(output, code);
        output.Append($"#include \"{path.Replace('\\', '/').Replace("\"", "\\\"")}\"\n");
        output.Append("#pragma GCC diagnostic push\n#pragma GCC diagnostic ignored \"-Winvalid-offsetof\"\n");
        foreach (Match m in ScriptClass().Matches(code))
        {
            string name = m.Groups["name"].Value;
            int open = code.IndexOf('{', m.Index + m.Length);
            int close = open < 0 ? -1 : ScriptTransform.MatchingBrace(code, open);
            if (close < 0)
            {
                Error(m.Index, $"The class {name} has no body.");
                continue;
            }
            var fields = new List<string>();
            var options = new List<string>();
            Members(source, code, open, close, m.Groups["kind"].Value == "struct", name, fields, options, Error);
            foreach (string option in options)
                output.Append(option).Append('\n');
            if (fields.Count > 0)
            {
                output.Append($"static const mh_field {name}__menhir_fields[] = {{\n");
                foreach (string field in fields)
                    output.Append("    ").Append(field).Append(",\n");
                output.Append("};\n");
                output.Append($"MENHIR_REGISTER({name}, {name}__menhir_fields, {fields.Count});\n");
            }
            else
                output.Append($"MENHIR_REGISTER({name}, nullptr, 0);\n");
        }
        output.Append("#pragma GCC diagnostic pop\n");
        return new ScriptTransformResult(diagnostics.Count == 0 ? output.ToString() : null, diagnostics);
    }

    /// <summary>MenhirScene.Name: one object per name the file uses, found by name (and remembered while it exists).</summary>
    private static void AppendScene(StringBuilder output, string code)
    {
        List<string> names = SceneObject().Matches(code).Select(m => m.Groups["name"].Value).Distinct().ToList();
        if (names.Count == 0)
            return;
        output.Append("struct MenhirSceneObjects : MenhirSceneBase {");
        foreach (string name in names)
            output.Append($" MenhirObject {name};");
        output.Append(" };\n");
        output.Append("static MenhirSceneObjects menhir__scene()\n{\n");
        output.Append($"    static mh_entity cache[{names.Count}] = {{ {string.Join(", ", names.Select(_ => "MH_NONE"))} }};\n");
        output.Append("    MenhirSceneObjects s;\n");
        for (int i = 0; i < names.Count; i++)
            output.Append($"    s.{names[i]} = MenhirObject(mh__scene_object(\"{names[i]}\", &cache[{i}]));\n");
        output.Append("    return s;\n}\n#undef MenhirScene\n#define MenhirScene (menhir__scene())\n");
    }

    /// <summary>The class body's public variables of the field types.</summary>
    private static void Members(string source, string code, int open, int close, bool isStruct, string className,
        List<string> fields, List<string> options, Action<int, string> error)
    {
        bool isPublic = isStruct;
        int start = open + 1;
        bool function = false;
        for (int i = open + 1; i < close; i++)
        {
            char c = code[i];
            if (i == SkipSpace(code, start) && Access().Match(code, i) is { Success: true } access && access.Index == i)
            {
                isPublic = access.Groups["access"].Value == "public";
                i += access.Length - 1;
                start = i + 1;
                continue;
            }
            if (c is '(' or '[')
            {
                function |= c == '(';
                i = ScriptTransform.MatchingBrace(code, i) is >= 0 and var end ? end : close;
                continue;
            }
            if (c == '{')
            {
                string head = code[start..i].Trim();
                int end = ScriptTransform.MatchingBrace(code, i);
                if (end < 0)
                    return;
                i = end;
                if (function || TypeKeyword().IsMatch(head) || head.Length == 0)
                {
                    // A function's body, or a type of its own: the statement ends there.
                    int next = SkipSpace(code, i + 1);
                    if (next < close && code[next] == ';')
                        i = next;
                    start = i + 1;
                    function = false;
                }
                continue;
            }
            if (c != ';')
                continue;
            if (isPublic && !function)
                Member(source, code, start, i, className, fields, options, error);
            start = i + 1;
            function = false;
        }
    }

    private static void Member(string source, string code, int start, int end, string className, List<string> fields,
        List<string> options, Action<int, string> error)
    {
        string text = code[start..end];
        string trimmed = text.Trim();
        if (trimmed.Length == 0 || NotAField().IsMatch(trimmed))
            return;
        int at = start + text.Length - text.TrimStart().Length;

        // "type name = value", "type name { values }" or "type name".
        string declaration;
        string? initializer = null;
        int equals = ScriptTransform.TopLevel(text, '=');
        int brace = text.IndexOf('{');
        if (equals >= 0)
        {
            declaration = text[..equals].Trim();
            initializer = source.Substring(start + equals + 1, end - start - equals - 1).Trim();
        }
        else if (brace >= 0)
        {
            declaration = text[..brace].Trim();
            initializer = source.Substring(start + brace, end - start - brace).Trim();
        }
        else
            declaration = trimmed;
        if (ScriptTransform.TopLevel(declaration, ',') >= 0)
            return; // several variables in one declaration: not fields
        Match d = Declarator().Match(declaration);
        if (!d.Success || d.Groups["array"].Value.Length > 0)
            return;
        string member = d.Groups["name"].Value;
        string type = Regex.Replace(d.Groups["type"].Value.Trim(), @"\s+", " ").Replace(" *", "*").Replace("* ", "*");
        if (KindOf(type) is not { } kind)
            return;

        string comment = ScriptTransform.CommentAfter(source, end);
        if (Regex.IsMatch(comment, @"\bMH_HIDE\b"))
            return;
        Match range = Regex.Match(comment, @"\bMH_RANGE\s*\(\s*(?<min>[^,()]+?)\s*,\s*(?<max>[^,()]+?)\s*\)");
        string tooltip = Regex.Replace(comment, @"\bMH_RANGE\s*\([^)]*\)", "").Trim();

        int count = kind switch { "MH_FIELD_VEC2" => 2, "MH_FIELD_VEC3" => 3, "MH_FIELD_COLOR" => 4, _ => 1 };
        string number = kind == "MH_FIELD_COLOR" ? "1, 1, 1, 1" : string.Join(", ", Enumerable.Repeat("0", count));
        string text_ = "\"\"";
        if (initializer is { Length: > 0 })
        {
            string value = initializer.StartsWith('{') && initializer.EndsWith('}') && count == 1 ? initializer[1..^1].Trim() : initializer;
            if (kind == "MH_FIELD_STRING")
            {
                if (!value.StartsWith('"'))
                {
                    error(at, $"The default of {member} is a text in quotes.");
                    return;
                }
                text_ = value;
            }
            else if (kind == "MH_FIELD_ENUM")
                number = $"(double)(int32_t)({value})";
            else if (count == 1)
                number = $"(double)({value})";
            else
            {
                List<string>? parts = ScriptTransform.Components(value);
                if (parts != null && kind == "MH_FIELD_COLOR" && parts.Count == 3)
                    parts.Add("1");
                if (parts == null || parts.Count != count)
                {
                    error(at, $"The default of {member} has {count} numbers: {{{string.Join(", ", Enumerable.Repeat("0", count))}}}.");
                    return;
                }
                number = string.Join(", ", parts.Select(p => $"(double)({p})"));
            }
        }

        var field = new StringBuilder($"{{ .name = \"{member}\", .kind = {kind}, .offset = (uint32_t)offsetof({className}, {member}), .number = {{ {number} }}");
        if (kind == "MH_FIELD_STRING")
            field.Append($", .text = {text_}");
        if (range.Success)
            field.Append($", .has_range = 1, .min = (float)({range.Groups["min"].Value}), .max = (float)({range.Groups["max"].Value})");
        if (tooltip.Length > 0)
            field.Append($", .tooltip = \"{tooltip.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"");
        if (kind == "MH_FIELD_ENUM")
        {
            string array = $"{className}__{member}__menhir_options";
            options.Add($"static const char *const {array}[] = {{ {string.Join(", ", StyleNames.Select(n => $"\"{n}\""))} }};");
            field.Append($", .options = {array}, .option_count = {StyleNames.Length}");
        }
        field.Append(" }");
        fields.Add(field.ToString());
    }

    /// <summary>MenhirStyle's values, in order (an enum field's options).</summary>
    private static readonly string[] StyleNames = ["Linear", "EaseIn", "EaseOut", "EaseInOut", "BackIn", "BackOut", "Elastic", "Bounce"];

    private static string? KindOf(string type) => type switch
    {
        "int" or "int32_t" => "MH_FIELD_INT",
        "float" => "MH_FIELD_FLOAT",
        "bool" => "MH_FIELD_BOOL",
        "MenhirVec2" => "MH_FIELD_VEC2",
        "MenhirVec3" or "MenhirPos" or "MenhirAngles" or "MenhirScale" => "MH_FIELD_VEC3",
        "MenhirColor" => "MH_FIELD_COLOR",
        "MenhirText" or "const char*" => "MH_FIELD_STRING",
        "MenhirStyle" => "MH_FIELD_ENUM",
        _ => null,
    };

    private static int SkipSpace(string code, int i)
    {
        while (i < code.Length && char.IsWhiteSpace(code[i]))
            i++;
        return i;
    }

    [GeneratedRegex(@"\b(?<kind>class|struct)\s+(?<name>[A-Za-z_]\w*)\s*(?:final\s*)?:\s*(?:(?:public|protected|private)\s+)?(?:virtual\s+)?MenhirEngine\b")]
    private static partial Regex ScriptClass();

    [GeneratedRegex(@"\bMenhirScene\s*\.\s*(?<name>[A-Za-z_]\w*)")]
    private static partial Regex SceneObject();

    [GeneratedRegex(@"\G(?<access>public|protected|private)\s*:(?!:)")]
    private static partial Regex Access();

    [GeneratedRegex(@"^(?:template\b|typedef\b|using\b|friend\b|enum\b|class\b|struct\b|union\b)|^(?:static|virtual|explicit|inline)\b.*$|\bstatic\b")]
    private static partial Regex NotAField();

    [GeneratedRegex(@"^(?:template\b|enum\b|class\b|struct\b|union\b|namespace\b)|\b(?:class|struct|enum|union)\b")]
    private static partial Regex TypeKeyword();

    [GeneratedRegex(@"^(?<type>.*?[\w\*&>\s:])(?<name>[A-Za-z_]\w*)\s*(?<array>(?:\[[^\]]*\]\s*)*)$", RegexOptions.Singleline)]
    private static partial Regex Declarator();
}
