using System.Reflection;
using System.Text;
using Menhir.Editor.Rendering.OpenGL;

namespace Menhir.Editor.Build;

/// <summary>
/// Makes the game's standalone main.c: Engine/Player/src/main.c with every local include
/// (<c>#include "..."</c>) pasted in once, glad's OpenGL loader included, and the shaders the
/// editor renders with as C strings (in place of <c>shaders.gen.h</c>). Only system headers and
/// GLFW's stay as includes.
/// </summary>
public static class PlayerSource
{
    public const string ShadersHeader = "shaders.gen.h";

    private static readonly Type[] ShaderClasses = [typeof(Shaders), typeof(SkyShaders), typeof(PostProcessShaders), typeof(ShadowShaders)];

    // Editor overlays (selection outline, grid), not drawn by the game.
    private static readonly HashSet<string> EditorOnly =
        [nameof(Shaders.UnlitFragment), nameof(Shaders.GridVertex), nameof(Shaders.GridFragment)];

    /// <param name="engineDirectory">The repository's Engine/ folder.</param>
    public static string Amalgamate(string engineDirectory)
    {
        string source = Path.Combine(engineDirectory, "Player", "src");
        string[] includePaths = [source, Path.Combine(engineDirectory, "ThirdParty", "glad", "include")];
        var output = new StringBuilder();
        output.Append("/* Generated by the Menhir editor (File > Build). Compile it with GLFW, e.g.\n")
              .Append("     cc -O2 main.c -I glfw/include libglfw3.a -lm -ldl -lpthread\n")
              .Append("   glad (gl.h) is under (WTFPL OR CC0-1.0) AND Apache-2.0; the rest is Menhir's. */\n");
        Paste(Path.Combine(source, "main.c"), includePaths, new HashSet<string>(), output);
        return output.ToString();
    }

    private static void Paste(string file, string[] includePaths, HashSet<string> pasted, StringBuilder output)
    {
        string fullPath = Path.GetFullPath(file);
        if (!pasted.Add(fullPath))
            return;
        output.Append($"/* ---- {Path.GetFileName(file)} ---- */\n");
        foreach (string line in File.ReadAllLines(fullPath))
        {
            string trimmed = line.TrimStart();
            if (trimmed.StartsWith("#include \"", StringComparison.Ordinal))
            {
                string name = trimmed["#include \"".Length..trimmed.IndexOf('"', "#include \"".Length)];
                if (name == ShadersHeader)
                {
                    if (pasted.Add(ShadersHeader))
                        output.Append(ShaderStrings());
                    continue;
                }
                string? found = new[] { Path.GetDirectoryName(fullPath)! }.Concat(includePaths)
                    .Select(directory => Path.Combine(directory, name)).FirstOrDefault(File.Exists);
                if (found == null)
                    throw new FileNotFoundException($"{Path.GetFileName(file)} includes \"{name}\", which is not in the engine.");
                Paste(found, includePaths, pasted, output);
                continue;
            }
            output.Append(line).Append('\n');
        }
    }

    /// <summary>Every shader the game uses as <c>static const char mh_shader_Class_Name[]</c>.</summary>
    public static string ShaderStrings()
    {
        var output = new StringBuilder("/* ---- shaders (from the editor's Rendering/Shaders) ---- */\n");
        foreach (Type type in ShaderClasses)
        {
            IEnumerable<FieldInfo> fields = type.GetFields(BindingFlags.Public | BindingFlags.Static)
                .Where(f => f.IsLiteral && f.FieldType == typeof(string))
                .Where(f => !(type == typeof(Shaders) && EditorOnly.Contains(f.Name)));
            foreach (FieldInfo field in fields)
            {
                output.Append($"static const char mh_shader_{type.Name}_{field.Name}[] =\n");
                string text = (string)field.GetRawConstantValue()!;
                string[] lines = text.Split('\n');
                foreach (string line in lines)
                    output.Append("    \"").Append(Escape(line)).Append("\\n\"\n");
                output.Append("    ;\n");
            }
        }
        return output.ToString();
    }

    /// <summary>A C string literal's contents; non-ASCII characters become octal escapes of their UTF-8 bytes.</summary>
    private static string Escape(string line)
    {
        var s = new StringBuilder();
        foreach (byte b in Encoding.UTF8.GetBytes(line.TrimEnd('\r')))
        {
            if (b == '\\' || b == '"')
                s.Append('\\').Append((char)b);
            else if (b == '\t')
                s.Append("\\t");
            else if (b < 32 || b > 126)
                s.Append('\\').Append(Convert.ToString(b, 8).PadLeft(3, '0'));
            else
                s.Append((char)b);
        }
        return s.ToString();
    }
}
